/** Adds an icon's strokes to the current path, fitted to a box. */
export function iconPath(vec, list, x, y, size) {
  for (const st of list) {
    vec.move(x + st[0] * size, y + st[1] * size);
    if (st.length === 2) vec.to(x + st[0] * size + 0.6, y + st[1] * size + 0.6);
    for (let i = 2; i < st.length; i += 2) vec.to(x + st[i] * size, y + st[i + 1] * size);
  }
}
